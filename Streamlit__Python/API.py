#What is API? 
"""API stands for Application Programming Interface. 
It is a set of rules and protocols that allows different software applications to 
communicate with each other. 
An API defines how requests and responses should be structured, 
enabling developers to access and use the functionality of another application 
or service without needing to understand its internal workings. 
APIs are commonly used for web services, allowing applications to interact with each other
 over the internet."""

"""User to api client, api client to api server, api server to database, 
database to api server, api server to api client, api client to user.
Here api client is the one who is sending the request to the api server, 
and api server is the one who is processing the request and 
sending the response back to the api client."""